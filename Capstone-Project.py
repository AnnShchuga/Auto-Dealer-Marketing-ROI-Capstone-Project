#Counting LTV and ROI

df_ltv = pd.merge(df[df['Install_Date']>='2023-07-01'], df_company, how='left', on=['Campaign', 'Project_Name'])

df_ltv['user_cost'] = np.where(df_ltv['Organic'] == 'Yes', df_ltv['Advertising_Costs (USD)'] / df_ltv['Clicks'], 0)
df_ltv = df_ltv.groupby(['Install_Date'], as_index=False).agg({'User_ID':'nunique', 'Revenue (USD)': 'sum', 'user_cost': 'sum'}) \
           .rename(columns = {'User_ID':'Installs', 'Revenue (USD)': 'revenue', 'user_cost':'spend_daily'})

df_ltv['install_month'] = df_ltv['Install_Date'].dt.month
df_ltv = df_ltv.groupby(['install_month'], as_index = False).agg({'Installs':'sum', 'spend_daily':'sum', 'revenue':'sum'}) \
         .rename(columns = {'spend_daily':'spend_month', 'revenue': 'total_revenue'})
df_ltv['ltv'] = df_ltv['total_revenue'] / df_ltv['Installs']
df_ltv['cpi'] = df_ltv['spend_month'] / df_ltv['Installs']
df_ltv['roi'] = df_ltv['total_revenue']*100 / df_ltv['spend_month']

df_ltv

