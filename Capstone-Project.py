#Counting the CPI

df_spend = pd.merge(df[df['Install_Date']>='2023-07-01'], df_company, how='left', on=['Campaign', 'Project_Name'])

df_spend['user_cost'] = np.where(df_spend['Organic'] == 'Yes', df_spend['Advertising_Costs (USD)'] / df_spend['Clicks'], 0)
