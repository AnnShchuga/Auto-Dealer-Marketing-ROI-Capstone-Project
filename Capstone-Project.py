# DAU (Daily Active Users)
df_dau = df.groupby('Install_Date', as_index=False).agg({'User_ID':'nunique'}).rename(columns = {'User_ID':'dau'})

# PPU (Percentage of Paying Users (the share of the paying audience relative to DAU))
